// Workers have no filesystem at runtime, so markdown articles are read here at
// build time and emitted as a module the app imports.
import fs from "node:fs";
import path from "node:path";

const dirs = ["content/insights", "content/product-articles/rankout", "content/product-articles/comflo", "content/product-articles/checkout"];
const files = dirs
  .filter((dir) => fs.existsSync(dir))
  .flatMap((dir) => fs.readdirSync(dir)
    .filter((name) => /\.mdx?$/.test(name))
    .sort()
    .map((name) => ({ file: path.join(dir, name), name, raw: fs.readFileSync(path.join(dir, name), "utf8") })));

fs.mkdirSync("lib/generated", { recursive: true });
fs.writeFileSync(
  "lib/generated/content.ts",
  `// Generated by scripts/bundle-content.mjs. Do not edit.\n` +
    `export const contentFiles: { file: string; name: string; raw: string }[] = ${JSON.stringify(files)};\n`,
);
console.log(`bundled ${files.length} articles`);
